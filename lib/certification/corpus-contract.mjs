export function findDuplicateScenarioIds(scenarios = []) {
  const seen = new Set();
  const duplicates = new Set();
  for (const scenario of scenarios) {
    const id = scenario?.id;
    if (typeof id !== 'string' || !id) continue;
    if (seen.has(id)) duplicates.add(id);
    else seen.add(id);
  }
  return [...duplicates];
}

export function validateCorpusContract({ repoRoot } = {}) {
  const scenarios = listScenarios({ repoRoot });
  const duplicates = findDuplicateScenarioIds(scenarios);
  const errors = duplicates.map((id) => `duplicate scenario id across catalogs: ${id}`);
  return { pass: errors.length === 0, errors, scenarioCount: scenarios.length, duplicates };
}
