/**
 * lib/certification/skill-scenarios.mjs — workflow skill certification scenario fixtures.
 *
 * Authors positive and negative hermetic scenario fixtures per workflow skill.
 * Negative scenarios assert typed failure metadata without writing outside tmpdir.
 */

import fs from 'node:fs';
import path from 'node:path';

import { validateSkillEffectiveness } from '../validators/skill-effectiveness.mjs';
import { auditSkillComposition } from '../skills/composition-graph.mjs';
import { defaultSkillInventoryPath } from './skill-inventory.mjs';
import { defaultScenarioCatalogPath } from './scenarios.mjs';

const HIGH_RISK_SKILLS = null;

function highRiskSkillIds(root) {
  if (HIGH_RISK_SKILLS) return HIGH_RISK_SKILLS;
  const file = defaultSkillInventoryPath(root);
  const inventory = JSON.parse(fs.readFileSync(file, 'utf8'));
  return new Set((inventory.skills ?? []).filter((s) => s.workflowSkill).map((s) => s.id));
}

function findConstructRoot(startPath = process.cwd()) {
  let current = path.resolve(startPath);
  while (true) {
    if (fs.existsSync(path.join(current, 'package.json')) && fs.existsSync(path.join(current, 'tests'))) return current;
    const parent = path.dirname(current);
    if (parent === current) return path.resolve(startPath);
    current = parent;
  }
}

export function skillScenarioDir(skillId, { rootDir } = {}) {
  const root = findConstructRoot(rootDir);
  return path.join(root, 'tests', 'certification', 'scenarios', 'skills', skillId.replace(/\//g, '__'));
}

function loadWorkflowSkills(rootDir) {
  const file = defaultSkillInventoryPath(rootDir);
  const inventory = JSON.parse(fs.readFileSync(file, 'utf8'));
  return (inventory.skills ?? []).filter((s) => s.workflowSkill === true);
}

export function buildPositiveScenario(skill) {
  return {
    skillId: skill.id,
    mode: 'positive',
    activationTriggers: skill.activationTriggers ?? [],
    inputs: skill.inputs ?? [],
    expectedOutputs: skill.outputs ?? {},
    verificationSteps: [
      'skill file exists under skills/',
      'inventory lists owners and workflowSkill=true',
      'effectiveness rubric passes (lint:scopes)',
      'get_skill and specialist refs resolve (composition graph)',
    ],
    owners: skill.owners ?? [],
  };
}

export function buildNegativeScenario(skill) {
  return {
    skillId: skill.id,
    mode: 'negative',
    failureClass: 'policy-denial',
    input: { missingPrerequisite: true, skillId: skill.id },
    expected: {
      graceful: true,
      errorType: 'SKILL_PREREQUISITE_MISSING',
      silentSuccess: false,
    },
    note: 'Hermetic fixture — runner classifies failure without filesystem writes',
  };
}

export function validateSkillScenarioFixture(fixture, { rootDir } = {}) {
  const root = findConstructRoot(rootDir);
  const errors = [];
  if (!fixture?.skillId) errors.push('skillId required');
  if (!fixture?.mode) errors.push('mode required');
  const skillPath = path.join(root, 'skills', `${fixture.skillId}.md`);
  if (!fs.existsSync(skillPath)) errors.push(`missing skill file: skills/${fixture.skillId}.md`);
  if (fixture.mode === 'positive' && !Array.isArray(fixture.verificationSteps)) {
    errors.push('positive fixture requires verificationSteps');
  }
  if (fixture.mode === 'positive' && fixture.verificationSteps?.includes('effectiveness rubric passes (lint:scopes)')) {
    const eff = validateSkillEffectiveness({ rootDir: root });
    if (!eff.valid) errors.push(`effectiveness: ${eff.errors.find((e) => e.startsWith(fixture.skillId)) ?? eff.errors[0]}`);
  }
  if (fixture.mode === 'positive' && fixture.verificationSteps?.includes('get_skill and specialist refs resolve (composition graph)')) {
    const comp = auditSkillComposition({ rootDir: root });
    if (!comp.pass) errors.push(`composition: ${comp.blocking[0] ?? 'blocking'}`);
  }
  if (fixture.mode === 'negative') {
    if (fixture.expected?.silentSuccess !== false) errors.push('negative fixture must forbid silent success');
    if (!fixture.expected?.errorType) errors.push('negative fixture requires expected.errorType');
  }
  return { pass: errors.length === 0, errors };
}

export function writeSkillScenarioFixtures({ rootDir } = {}) {
  const root = findConstructRoot(rootDir);
  const skills = loadWorkflowSkills(root);
  const readme = path.join(root, 'tests', 'certification', 'scenarios', 'skills', 'README.md');
  fs.mkdirSync(path.dirname(readme), { recursive: true });
  const lines = [
    '<!--',
    'tests/certification/scenarios/skills/README.md — workflow skill certification scenario index.',
    '',
    'Generated by lib/certification/skill-scenarios.mjs; lists positive and negative fixtures per workflow skill.',
    '-->',
    '',
    '# Workflow skill certification scenarios',
    '',
    'Hermetic positive and negative fixtures per workflow skill. Synced by `lib/certification/skill-scenarios.mjs`.',
    '',
  ];
  const catalogEntries = [];
  for (const skill of skills) {
    const dir = skillScenarioDir(skill.id, { rootDir: root });
    fs.mkdirSync(dir, { recursive: true });
    const positive = buildPositiveScenario(skill);
    const positivePath = path.join(dir, 'positive.json');
    fs.writeFileSync(positivePath, `${JSON.stringify(positive, null, 2)}\n`);
    const relPositive = path.relative(root, positivePath);
    catalogEntries.push({
      id: `skill.positive.${skill.id.replace(/\//g, '.')}`,
      capabilityId: 'skills.workflow',
      mode: 'hermetic',
      fixture: { path: relPositive },
      gates: [{ id: `skill-positive-${skill.id}`, type: 'skill-scenario-audit' }],
      model: { provider: 'hermetic', requestedId: 'fixture/skill', resolvedId: 'fixture/skill', tier: 'hermetic' },
    });
    lines.push(`- \`${skill.id}\` — positive: \`${relPositive}\``);
    if (highRiskSkillIds(root).has(skill.id)) {
      const negative = buildNegativeScenario(skill);
      const negativePath = path.join(dir, 'negative.json');
      fs.writeFileSync(negativePath, `${JSON.stringify(negative, null, 2)}\n`);
      const relNegative = path.relative(root, negativePath);
      catalogEntries.push({
        id: `skill.negative.${skill.id.replace(/\//g, '.')}`,
        capabilityId: 'skills.workflow',
        mode: 'hermetic',
        fixture: { path: relNegative },
        gates: [{ id: `skill-negative-${skill.id}`, type: 'skill-scenario-audit' }],
        model: { provider: 'hermetic', requestedId: 'fixture/skill', resolvedId: 'fixture/skill', tier: 'hermetic' },
      });
      lines.push(`  - negative: \`${relNegative}\``);
    }
  }
  fs.writeFileSync(readme, `${lines.join('\n')}\n`);
  const catalogPath = defaultScenarioCatalogPath(root);
  const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
  const keep = (catalog.scenarios ?? []).filter((s) => !String(s.id).startsWith('skill.'));
  catalog.scenarios = [...keep, ...catalogEntries];
  fs.writeFileSync(catalogPath, `${JSON.stringify(catalog, null, 2)}\n`);
  return { skillCount: skills.length, catalogEntries: catalogEntries.length, readme };
}
