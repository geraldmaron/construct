#!/usr/bin/env node
/**
 * inventory-sync-era.mjs — read-only sweep of a directory of many projects for
 * artifacts an earlier construct-sync left behind: rule files, MCP entries,
 * skill trees, and agent/prompt files planted into a project's own checkout
 * rather than authored by it.
 *
 * This is NOT `construct cleanup`'s predecessor-litter catalog
 * (src/kernel/cleanup/catalog.ts). That catalog inspects ONE project (the cwd)
 * for a different predecessor's traces, by a different set of signatures, and
 * it can remove what it finds. This script only looks, across MANY projects
 * under one root, for a narrower and different set of markers, and never
 * writes or deletes anything — it produces a manifest a person or a later,
 * separate step acts on.
 *
 * Detection is marker-driven, not a hardcoded file list: a generation marker
 * has to actually appear in a file (or, for .cursor/mcp.json, inside a parsed
 * server entry) before anything is reported. The five target locations below
 * only narrow WHERE the marker search looks; they do not themselves count as
 * hits.
 *
 * Usage:
 *   node scripts/inventory-sync-era.mjs [root] [--json]
 *
 * root defaults to ~/Developer/Projects, resolved from the real home
 * directory via os.homedir() — never a hardcoded path.
 */

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

// ---------------------------------------------------------------------------
// Markers
// ---------------------------------------------------------------------------

/** The generation markers a construct-sync-era artifact carries. */
export const MARKERS = Object.freeze([
  'Generated by construct sync',
  '@geraldmaron/construct',
  'orchestration_run',
]);

/** Which of MARKERS appear in `text`, in MARKERS order. Never throws. */
export function markersIn(text) {
  if (typeof text !== 'string' || text.length === 0) return [];
  return MARKERS.filter((marker) => text.includes(marker));
}

// ---------------------------------------------------------------------------
// construct-repo exclusion
// ---------------------------------------------------------------------------

/**
 * Whether `dir` is a checkout of THIS repo rather than a project it was
 * synced into. Signal: dir/package.json parses as JSON and its "name" field
 * is exactly the package name this repo publishes under. That is a fact a
 * real checkout of this repo carries (see package.json at the repo root);
 * a basename guess ("is the folder called construct?") would misfire on any
 * unrelated project someone happened to name that, and would miss this repo
 * if it were checked out under a different folder name.
 */
export function looksLikeConstructRepo(dir) {
  let raw;
  try {
    raw = fs.readFileSync(path.join(dir, 'package.json'), 'utf8');
  } catch {
    return false;
  }
  try {
    const pkg = JSON.parse(raw);
    return Boolean(pkg) && pkg.name === '@geraldmaron/construct';
  } catch {
    return false;
  }
}

// ---------------------------------------------------------------------------
// Filesystem helpers — every read is wrapped so one unreadable path skips
// itself and gets noted, instead of crashing the whole walk.
// ---------------------------------------------------------------------------

function listDir(dir) {
  try {
    return { entries: fs.readdirSync(dir, { withFileTypes: true }) };
  } catch (err) {
    return { error: err };
  }
}

function readTextSafe(filePath) {
  try {
    return fs.readFileSync(filePath, 'utf8');
  } catch {
    return null;
  }
}

/**
 * Every regular file under `dir`, recursively, skipping node_modules and not
 * following symlinks (a synced tree should not have any, and refusing to
 * follow avoids both cycles and wandering outside the project). Permission
 * errors and other unreadable directories are pushed onto `notes` and
 * skipped rather than thrown.
 */
function walkFiles(dir, notes, out) {
  const { entries, error } = listDir(dir);
  if (error) {
    if (error.code !== 'ENOENT') notes.push(`skipped ${dir}: ${error.code || error.message}`);
    return;
  }
  for (const entry of entries) {
    if (entry.name === 'node_modules') continue;
    if (entry.isSymbolicLink()) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkFiles(full, notes, out);
    else if (entry.isFile()) out.push(full);
  }
}

// ---------------------------------------------------------------------------
// Per-target-location scans. Each returns hits: { file, marker, class }.
// `file` is relative to the project directory, for a readable manifest.
// ---------------------------------------------------------------------------

/**
 * .cursor/rules/construct-*.mdc — the filename glob narrows which files get
 * their content searched; a marker still has to appear in that content.
 */
export function scanCursorRules(projectDir, notes) {
  const dir = path.join(projectDir, '.cursor', 'rules');
  const { entries, error } = listDir(dir);
  if (error) {
    if (error.code !== 'ENOENT') notes.push(`skipped ${dir}: ${error.code || error.message}`);
    return [];
  }
  const hits = [];
  for (const entry of entries) {
    if (!entry.isFile() || !/^construct-.*\.mdc$/.test(entry.name)) continue;
    const full = path.join(dir, entry.name);
    const content = readTextSafe(full);
    if (content === null) {
      notes.push(`skipped ${full}: unreadable`);
      continue;
    }
    for (const marker of markersIn(content)) {
      hits.push({ file: path.relative(projectDir, full), marker, class: 'cursor-rule' });
    }
  }
  return hits;
}

/**
 * .cursor/mcp.json construct-related entries. Parsed as JSON rather than
 * grepped as text: only the mcpServers container's own entries are searched,
 * so a marker string sitting in some unrelated field of the file (or in a
 * sibling project's copy-pasted comment) cannot produce a false hit the way a
 * whole-file text grep would. An entry counts as a hit when a marker appears
 * anywhere in its own serialized id+value — the id, command, args, or env.
 */
export function scanCursorMcp(projectDir, notes) {
  const file = path.join(projectDir, '.cursor', 'mcp.json');
  const raw = readTextSafe(file);
  if (raw === null) return [];
  let config;
  try {
    config = JSON.parse(raw);
  } catch {
    notes.push(`skipped ${file}: malformed JSON`);
    return [];
  }
  const servers = config && typeof config === 'object' ? config.mcpServers : null;
  if (!servers || typeof servers !== 'object') return [];

  const hits = [];
  for (const [id, entry] of Object.entries(servers)) {
    const serialized = JSON.stringify({ [id]: entry });
    for (const marker of markersIn(serialized)) {
      hits.push({
        file: path.relative(projectDir, file),
        marker,
        class: 'mcp-entry',
        detail: `mcpServers.${id}`,
      });
    }
  }
  return hits;
}

/**
 * A tree of files under `subdir`, each searched for markers. Used for
 * .claude/skills (signal: a marker string appears in some file under the
 * tree — the concrete stand-in for "looks synced rather than authored",
 * since a synced skill carries the same generated header a synced rule
 * file does, and an authored one has no reason to) and for .github/agents
 * and .github/prompts.
 */
function scanMarkerTree(projectDir, subdirParts, artifactClass, notes) {
  const dir = path.join(projectDir, ...subdirParts);
  const files = [];
  walkFiles(dir, notes, files);
  const hits = [];
  for (const full of files) {
    const content = readTextSafe(full);
    if (content === null) {
      notes.push(`skipped ${full}: unreadable`);
      continue;
    }
    for (const marker of markersIn(content)) {
      hits.push({ file: path.relative(projectDir, full), marker, class: artifactClass });
    }
  }
  return hits;
}

export function scanSkillsTree(projectDir, notes) {
  return scanMarkerTree(projectDir, ['.claude', 'skills'], 'skills-tree', notes);
}

export function scanGithubAgents(projectDir, notes) {
  return scanMarkerTree(projectDir, ['.github', 'agents'], 'github-agent', notes);
}

export function scanGithubPrompts(projectDir, notes) {
  return scanMarkerTree(projectDir, ['.github', 'prompts'], 'github-prompt', notes);
}

/** All five target locations for one project. Never throws. */
export function scanProject(projectDir) {
  const notes = [];
  const hits = [
    ...scanCursorRules(projectDir, notes),
    ...scanCursorMcp(projectDir, notes),
    ...scanSkillsTree(projectDir, notes),
    ...scanGithubAgents(projectDir, notes),
    ...scanGithubPrompts(projectDir, notes),
  ];
  return { hits, notes };
}

// ---------------------------------------------------------------------------
// Root walk
// ---------------------------------------------------------------------------

/**
 * Scans every immediate child directory of `root` as one project. Returns
 * `{ status: 'no-root' }` when root does not exist (or is not readable as a
 * directory) — a machine without that directory is not an error, it is the
 * expected state on any machine other than Gerald's. Otherwise returns
 * `{ status: 'ok', projects, scanned, excludedConstructRepo, clean }` where
 * `projects` holds every non-excluded project that had a hit OR a note (a
 * partially-unreadable project is never silently reported as clean).
 */
export function inventory(root) {
  const { entries, error } = listDir(root);
  if (error) {
    if (error.code === 'ENOENT') return { status: 'no-root', reason: 'does not exist' };
    return { status: 'no-root', reason: error.code || error.message };
  }

  const projects = [];
  let scanned = 0;
  let excludedConstructRepo = 0;
  let clean = 0;

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const projectDir = path.join(root, entry.name);
    if (looksLikeConstructRepo(projectDir)) {
      excludedConstructRepo += 1;
      continue;
    }
    scanned += 1;
    const { hits, notes } = scanProject(projectDir);
    if (hits.length === 0 && notes.length === 0) {
      clean += 1;
      continue;
    }
    if (hits.length === 0) clean += 1;
    projects.push({ name: entry.name, path: projectDir, hits, notes });
  }

  return { status: 'ok', projects, scanned, excludedConstructRepo, clean };
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function defaultRoot() {
  return path.join(os.homedir(), 'Developer', 'Projects');
}

function printManifest(result, root) {
  if (result.status === 'no-root') {
    console.log(`inventory-sync-era: root ${root} ${result.reason} — nothing to scan.`);
    return 0;
  }

  for (const project of result.projects) {
    if (project.hits.length > 0) {
      console.log(project.path);
      for (const hit of project.hits) {
        const detail = hit.detail ? ` (${hit.detail})` : '';
        console.log(`  ${hit.class.padEnd(13)} ${hit.marker.padEnd(28)} ${hit.file}${detail}`);
      }
    } else {
      // Hit-free but not silent: at least one target location under this
      // project could not be fully read, so "clean" here means "clean of
      // what could be read", not a guarantee.
      console.log(`${project.path}  (scan incomplete, no hits in what was readable)`);
    }
    for (const note of project.notes) console.log(`  note: ${note}`);
  }

  const withHits = result.projects.filter((p) => p.hits.length > 0).length;
  console.log(
    `\ninventory-sync-era: ${result.scanned} project(s) scanned under ${root}, ` +
      `${withHits} with hits, ${result.clean} clean` +
      (result.excludedConstructRepo > 0
        ? `, ${result.excludedConstructRepo} excluded (this repo)`
        : '') +
      '.',
  );
  return 0;
}

function printManifestJson(result, root) {
  console.log(JSON.stringify({ root, ...result }, null, 2));
  return 0;
}

function main() {
  const args = process.argv.slice(2);
  const jsonMode = args.includes('--json');
  const positional = args.find((a) => !a.startsWith('--'));
  const root = positional ? path.resolve(positional) : defaultRoot();

  const result = inventory(root);
  const code = jsonMode ? printManifestJson(result, root) : printManifest(result, root);
  process.exit(code);
}

// Only when run as a script. Importing this file (the tests do) must not
// walk a filesystem or exit the process.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
