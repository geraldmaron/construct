#!/usr/bin/env node
/**
 * inventory-sync-era.mjs — enumerate leftover 2.x `construct sync` artifacts
 * across project trees, read-only.
 *
 * The predecessor pushed rules, MCP entries, skill folders, and GitHub
 * agent/prompt files into other repos and then forgot them. Cleanup that
 * starts from a hardcoded file list misses the next tree; this walk starts
 * from generation markers and the well-known target locations, then prints
 * a per-project manifest. It never writes.
 *
 * Usage:
 *   node scripts/inventory-sync-era.mjs [--root <dir>] [--json]
 *
 * Default root is $HOME/Developer/Projects. Tests pass --root at a tmpdir
 * so they never touch a real home. The rewrite's own checkout (a directory
 * named `construct`) is skipped, as is node_modules.
 */

import { existsSync, lstatSync, readdirSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, join, relative } from 'node:path';

const MARKERS = ['Generated by construct sync', '@geraldmaron/construct', 'orchestration_run'];

const JSON_MODE = process.argv.includes('--json');
const rootIdx = process.argv.indexOf('--root');
const ROOT =
  rootIdx >= 0 && process.argv[rootIdx + 1]
    ? process.argv[rootIdx + 1]
    : join(homedir(), 'Developer', 'Projects');

/** Skip the rewrite itself and package installs. */
const SKIP_TOP = new Set(['construct', 'node_modules', '.git']);

/**
 * @typedef {{ path: string, class: string, markers: string[] }} Artifact
 * @typedef {{ name: string, artifacts: Artifact[] }} Project
 */

function markersIn(text) {
  return MARKERS.filter((m) => text.includes(m));
}

function readText(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
}

function classify(rel) {
  if (rel.startsWith('.cursor/rules/') && /^construct-.*\.mdc$/.test(basename(rel))) {
    return 'cursor-rule';
  }
  if (rel === '.cursor/mcp.json') return 'cursor-mcp';
  if (rel === '.vscode/mcp.json') return 'vscode-mcp';
  if (rel.startsWith('.claude/skills/')) return 'claude-skill';
  if (rel.startsWith('.github/agents/')) return 'github-agent';
  if (rel.startsWith('.github/prompts/')) return 'github-prompt';
  return 'marker-hit';
}

function add(artifacts, projectRoot, abs, extraMarkers = []) {
  const rel = relative(projectRoot, abs).split('\\').join('/');
  const found = [...new Set([...markersIn(readText(abs)), ...extraMarkers])];
  artifacts.push({ path: rel, class: classify(rel), markers: found });
}

function listFiles(dir) {
  if (!existsSync(dir) || !lstatSync(dir).isDirectory()) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => join(dir, e.name));
}

/**
 * Skills trees are mixed with the host's own. A skill is leftover sync only
 * when it names Construct or carries a generation marker — listing every
 * SKILL.md in the tree would report the project's own pack as litter.
 */
function walkSkillFiles(dir, skillsRoot, into) {
  if (!existsSync(dir) || !lstatSync(dir).isDirectory()) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === '.git') continue;
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) {
      walkSkillFiles(abs, skillsRoot, into);
      continue;
    }
    if (!entry.isFile()) continue;
    const rel = relative(skillsRoot, abs).split('\\').join('/');
    const text = readText(abs);
    const marked = markersIn(text);
    const named = /construct/i.test(rel);
    if (marked.length > 0 || named) into.push(abs);
  }
}

function scanProject(projectRoot) {
  /** @type {Artifact[]} */
  const artifacts = [];

  const rulesDir = join(projectRoot, '.cursor', 'rules');
  if (existsSync(rulesDir) && lstatSync(rulesDir).isDirectory()) {
    for (const name of readdirSync(rulesDir)) {
      if (!/^construct-.*\.mdc$/.test(name)) continue;
      add(artifacts, projectRoot, join(rulesDir, name));
    }
  }

  for (const rel of ['.cursor/mcp.json', '.vscode/mcp.json']) {
    const abs = join(projectRoot, rel);
    if (!existsSync(abs) || !lstatSync(abs).isFile()) continue;
    const text = readText(abs);
    if (
      text.includes('construct-mcp') ||
      text.includes('@geraldmaron/construct') ||
      text.includes('orchestration_run')
    ) {
      add(artifacts, projectRoot, abs);
    }
  }

  for (const relDir of ['.github/agents', '.github/prompts']) {
    for (const abs of listFiles(join(projectRoot, relDir))) {
      const name = basename(abs);
      const text = readText(abs);
      if (
        /^construct/i.test(name) ||
        name === '.construct-manifest' ||
        markersIn(text).length > 0
      ) {
        add(artifacts, projectRoot, abs);
      }
    }
  }

  const skillHits = [];
  const skillsRoot = join(projectRoot, '.claude', 'skills');
  walkSkillFiles(skillsRoot, skillsRoot, skillHits);
  for (const abs of skillHits) add(artifacts, projectRoot, abs);

  return artifacts;
}

function inventory(root) {
  if (!existsSync(root) || !lstatSync(root).isDirectory()) {
    return { root, error: `not a directory: ${root}`, projects: [] };
  }
  /** @type {Project[]} */
  const projects = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (SKIP_TOP.has(entry.name)) continue;
    const projectRoot = join(root, entry.name);
    const artifacts = scanProject(projectRoot);
    if (artifacts.length === 0) continue;
    projects.push({ name: entry.name, artifacts });
  }
  projects.sort((a, b) => a.name.localeCompare(b.name));
  return { root, projects };
}

function printHuman(result) {
  if (result.error) {
    process.stderr.write(`inventory-sync-era: ${result.error}\n`);
    return;
  }
  const total = result.projects.reduce((n, p) => n + p.artifacts.length, 0);
  process.stdout.write(
    `sync-era inventory: ${String(result.projects.length)} project(s), ${String(total)} artifact(s) (read-only)\n`,
  );
  for (const project of result.projects) {
    process.stdout.write(`\n${project.name}  (${String(project.artifacts.length)})\n`);
    for (const art of project.artifacts) {
      const marks = art.markers.length > 0 ? `  [${art.markers.join('; ')}]` : '';
      process.stdout.write(`  ${art.class.padEnd(14)} ${art.path}${marks}\n`);
    }
  }
}

const result = inventory(ROOT);
if (JSON_MODE) {
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
} else {
  printHuman(result);
}
process.exit(result.error ? 1 : 0);
