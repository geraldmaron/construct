#!/usr/bin/env node
/**
 * lint-skill-pack-skew.mjs: the committed skill pack under .claude/skills/
 * matches what the current role catalog would generate right now.
 *
 * `construct skills --out=.claude/skills` projects src/kernel/plan/lenses.ts
 * (plus playbooks and standards) into one SKILL.md per lens and writes it.
 * The result is committed, but nothing regenerates it: an edit to lenses.ts
 * with no follow-up run leaves a stale pack sitting in the tree, agreeing
 * with nothing the catalog currently says. This is the gate that notices.
 *
 * The comparison reuses the kernel's own projection rather than a second
 * copy of it: `projectSkillsPack` is pure (no filesystem, no environment, no
 * clock), so calling it here with the same lenses, playbooks, standards, and
 * version `construct skills` itself would use produces the exact bytes a
 * real run would write. What is on disk either matches that, byte for byte,
 * or the pack is stale.
 *
 * `skillPackSkew` (also from the kernel, also the function doctor's own
 * check calls) is reused as-is for the coarser, cheaper signal it already
 * computes: a folder stamped by a construct version other than the one that
 * would generate it now. That check alone cannot see a same-version content
 * edit (the ordinary case tonight: lenses.ts changes, package.json's version
 * does not), which is why the byte comparison below is the check that
 * actually gates. Both run; a folder can appear in both reports, once for
 * its stamp and once for its content, and that is two true facts about the
 * same folder, not a duplicate.
 *
 * Only folders this generator actually wrote are judged, the same test
 * planSkillsUninstall uses before it will remove one: `isGeneratedSkill`
 * reads the `generator: construct` marker in the folder's own frontmatter.
 * A hand-authored skill sitting in the same directory carries no such
 * marker and is not this lint's business.
 */

import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { LENSES } from '../src/kernel/plan/lenses.ts';
import { allPlaybooks } from '../src/kernel/plan/playbooks.ts';
import { LENS_STANDARDS } from '../src/kernel/plan/standards.ts';
import { isGeneratedSkill, projectSkillsPack, skillPackSkew } from '../src/kernel/skills/projection.ts';
import { packageVersion } from '../src/cli/runtime.ts';
import { readSkillFolders } from '../src/cli/skills.ts';

/**
 * The repository this lint checks. Overridable by a first CLI argument, the
 * same seam lint-doc-commands.mjs and lint-doc-bead-refs.mjs carry: a test
 * needs somewhere sterile to plant a fixture pack instead of writing into
 * the real .claude/skills/ every other session and gate run shares. The
 * bare invocation `npm run lint` calls (no argument) resolves exactly as
 * before. The catalog itself is never overridable this way: lenses.ts,
 * playbooks, and standards are this checkout's own, always, because a
 * fixture catalog would be testing a lint that no longer exists.
 */
const ROOT = process.argv[2]
  ? resolve(process.argv[2])
  : fileURLToPath(new URL('../', import.meta.url));

const PACK_DIR = join(ROOT, '.claude', 'skills');
const installed = packageVersion();

const fresh = projectSkillsPack({
  lenses: LENSES,
  playbooks: allPlaybooks(),
  standards: LENS_STANDARDS,
  version: installed,
});
const freshByDirectory = new Map(fresh.map((file) => [file.directory, file.content]));

const committed = existsSync(PACK_DIR) ? readSkillFolders(PACK_DIR) : [];
const committedGenerated = new Map(
  committed
    .filter((folder) => folder.skill !== null && isGeneratedSkill(folder.skill))
    .map((folder) => [folder.directory, folder.skill]),
);

const problems = [];

for (const stamped of skillPackSkew(committed, installed)) {
  problems.push(`skill pack carries a folder stamped construct ${stamped}, current construct is ${installed}`);
}

for (const [directory, content] of freshByDirectory) {
  const have = committedGenerated.get(directory);
  if (have === undefined) {
    problems.push(`${directory}: the current catalog projects this skill, but .claude/skills/${directory}/SKILL.md is missing`);
  } else if (have !== content) {
    problems.push(`${directory}: committed SKILL.md does not match what the current catalog would generate`);
  }
}

for (const directory of committedGenerated.keys()) {
  if (!freshByDirectory.has(directory)) {
    problems.push(`${directory}: committed and generated by construct, but the current catalog no longer projects a skill by that name`);
  }
}

if (problems.length > 0) {
  for (const problem of problems) {
    process.stderr.write(`lint-skill-pack-skew: ${problem}\n`);
  }
  process.stderr.write(
    `\nlint-skill-pack-skew: ${String(problems.length)} folder(s) out of step with the catalog. ` +
      'Regenerate with: construct skills --out=.claude/skills\n',
  );
  process.exit(1);
}

process.stdout.write(
  `lint-skill-pack-skew: clean, ${String(freshByDirectory.size)} skill folder(s) match what the current catalog would generate\n`,
);
