test('looksLikeConstructRepo is true only for the exact published package name', () => {
  const dir = mkTmp('construct-inv-repo-');
  try {
    write(path.join(dir, 'package.json'), JSON.stringify({ name: '@geraldmaron/construct' }));
    assert.equal(looksLikeConstructRepo(dir), true);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('looksLikeConstructRepo is false for an unrelated project, a missing package.json, and malformed JSON', () => {
  const unrelated = mkTmp('construct-inv-unrelated-');
  const missing = mkTmp('construct-inv-missing-');
  const malformed = mkTmp('construct-inv-malformed-');
  try {
    // A project merely NAMED "construct" must not match — the signal is the
    // published package name, not a directory basename guess.
    write(path.join(unrelated, 'package.json'), JSON.stringify({ name: 'construct' }));
    assert.equal(looksLikeConstructRepo(unrelated), false);

    assert.equal(looksLikeConstructRepo(missing), false);

    write(path.join(malformed, 'package.json'), '{ not json');
    assert.equal(looksLikeConstructRepo(malformed), false);
  } finally {
    fs.rmSync(unrelated, { recursive: true, force: true });
    fs.rmSync(missing, { recursive: true, force: true });
    fs.rmSync(malformed, { recursive: true, force: true });
  }
});

