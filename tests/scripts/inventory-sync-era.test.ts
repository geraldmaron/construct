test('scanCursorRules matches only construct-*.mdc files, and only when a marker is inside', () => {
  const dir = mkTmp('construct-inv-rules-');
  try {
    write(
      path.join(dir, '.cursor', 'rules', 'construct-legacy.mdc'),
      'Generated by construct sync\nsome rule body',
    );
    // Same directory, filename doesn't match the glob: never searched.
    write(path.join(dir, '.cursor', 'rules', 'unrelated.mdc'), 'orchestration_run');
    // Matches the glob but carries no marker: not a hit.
    write(path.join(dir, '.cursor', 'rules', 'construct-clean.mdc'), 'nothing marked here');

    const notes: string[] = [];
    const hits = scanCursorRules(dir, notes);
    assert.equal(hits.length, 1);
    assert.equal(hits[0].class, 'cursor-rule');
    assert.equal(hits[0].marker, 'Generated by construct sync');
    assert.equal(hits[0].file, path.join('.cursor', 'rules', 'construct-legacy.mdc'));
    assert.deepEqual(notes, []);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('scanCursorRules also matches bare construct.mdc and construct.<word>.mdc, not only the hyphenated form', () => {
  const dir = mkTmp('construct-inv-rules-forms-');
  try {
    // The front-door rule file — no separator at all after "construct".
    write(path.join(dir, '.cursor', 'rules', 'construct.mdc'), 'Generated by construct sync');
    // A dotted variant, the other named form.
    write(path.join(dir, '.cursor', 'rules', 'construct.legacy.mdc'), '@geraldmaron/construct');
    // Starts with "construct" but has no separator before its own word —
    // must still not match, the same way "construct-*" never matched
    // "constructive-something.mdc".
    write(path.join(dir, '.cursor', 'rules', 'constructive.mdc'), 'orchestration_run');

    const notes: string[] = [];
    const hits = scanCursorRules(dir, notes);
    assert.deepEqual(
      hits.map((h: { file: string }) => h.file).sort(),
      [path.join('.cursor', 'rules', 'construct.legacy.mdc'), path.join('.cursor', 'rules', 'construct.mdc')].sort(),
    );
    assert.deepEqual(notes, []);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('scanCursorRules with no .cursor/rules directory reports no hits and no note', () => {
  const dir = mkTmp('construct-inv-norules-');
  try {
    const notes: string[] = [];
    assert.deepEqual(scanCursorRules(dir, notes), []);
    assert.deepEqual(notes, [], 'a directory simply not existing is not an error to report');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('scanCursorMcp parses mcpServers entries rather than grepping the raw file', () => {
  const dir = mkTmp('construct-inv-mcp-');
  try {
    write(
      path.join(dir, '.cursor', 'mcp.json'),
      JSON.stringify({
        // A marker sitting OUTSIDE mcpServers must not produce a hit — this is
        // exactly what a whole-file text grep would over-match on.
        _comment: 'orchestration_run appears here but is not a server entry',
        mcpServers: {
          'construct-mcp': {
            command: 'node',
            args: ['/path/to/@geraldmaron/construct/bin/construct.mjs', 'serve'],
          },
          github: { command: 'npx', args: ['-y', 'github-mcp'] },
        },
      }),
    );
    const notes: string[] = [];
    const hits = scanCursorMcp(dir, notes);
    assert.equal(hits.length, 1);
    assert.equal(hits[0].class, 'mcp-entry');
    assert.equal(hits[0].marker, '@geraldmaron/construct');
    assert.equal(hits[0].detail, 'mcpServers.construct-mcp');
    assert.deepEqual(notes, []);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('scanCursorMcp handles a missing file and malformed JSON without throwing', () => {
  const missing = mkTmp('construct-inv-mcp-missing-');
  const malformed = mkTmp('construct-inv-mcp-malformed-');
  try {
    assert.deepEqual(scanCursorMcp(missing, []), []);

    write(path.join(malformed, '.cursor', 'mcp.json'), '{ not json at all');
    const notes: string[] = [];
    assert.deepEqual(scanCursorMcp(malformed, notes), []);
    assert.ok(notes.some((n) => n.includes('malformed JSON')));
  } finally {
    fs.rmSync(missing, { recursive: true, force: true });
    fs.rmSync(malformed, { recursive: true, force: true });
  }
});

test('scanSkillsTree, scanGithubAgents, scanGithubPrompts walk their trees recursively and skip node_modules', () => {
  const dir = mkTmp('construct-inv-trees-');
  try {
    write(
      path.join(dir, '.claude', 'skills', 'deploy', 'nested', 'SKILL.md'),
      '<!-- Generated by construct sync -->',
    );
    write(
      path.join(dir, '.claude', 'skills', 'node_modules', 'pkg', 'file.md'),
      'orchestration_run',
    );
    write(path.join(dir, '.github', 'agents', 'construct.md'), 'orchestration_run');
    write(path.join(dir, '.github', 'prompts', 'sync.md'), '@geraldmaron/construct');

    const skillHits = scanSkillsTree(dir, []);
    assert.equal(skillHits.length, 1, 'node_modules under the tree must not be walked');
    assert.equal(skillHits[0].class, 'skills-tree');
    assert.equal(
      skillHits[0].file,
      path.join('.claude', 'skills', 'deploy', 'nested', 'SKILL.md'),
    );

    const agentHits = scanGithubAgents(dir, []);
    assert.equal(agentHits.length, 1);
    assert.equal(agentHits[0].class, 'github-agent');

    const promptHits = scanGithubPrompts(dir, []);
    assert.equal(promptHits.length, 1);
    assert.equal(promptHits[0].class, 'github-prompt');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('scanGithubAgents and scanGithubPrompts name an orphaned .construct-manifest sidecar, which carries no marker of its own', () => {
  const dir = mkTmp('construct-inv-manifest-');
  try {
    // Each sidecar's whole content is the filename of the artifact it used
    // to sit beside — no generated-artifact file exists here, matching the
    // deleted-artifact state a real orphaned sidecar is found in.
    write(path.join(dir, '.github', 'agents', '.construct-manifest'), 'construct.agent.md\n');
    write(path.join(dir, '.github', 'prompts', '.construct-manifest'), 'construct.prompt.md\n');

    const agentHits = scanGithubAgents(dir, []);
    assert.equal(agentHits.length, 1, 'no marker anywhere in this tree — the sidecar itself is the only signal');
    assert.equal(agentHits[0].class, 'github-agent-manifest');
    assert.equal(agentHits[0].file, path.join('.github', 'agents', '.construct-manifest'));
    assert.equal(agentHits[0].detail, 'construct.agent.md', 'names the deleted artifact it pointed at');

    const promptHits = scanGithubPrompts(dir, []);
    assert.equal(promptHits.length, 1);
    assert.equal(promptHits[0].class, 'github-prompt-manifest');
    assert.equal(promptHits[0].detail, 'construct.prompt.md');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('scanGithubAgents reports both a marker hit and a manifest sidecar when a tree carries both', () => {
  const dir = mkTmp('construct-inv-manifest-both-');
  try {
    write(path.join(dir, '.github', 'agents', 'still-generated.md'), 'orchestration_run');
    write(path.join(dir, '.github', 'agents', '.construct-manifest'), 'deleted.agent.md\n');

    const hits = scanGithubAgents(dir, []);
    assert.equal(hits.length, 2);
    assert.deepEqual(hits.map((h: { class: string }) => h.class).sort(), ['github-agent', 'github-agent-manifest']);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('an unreadable target location is skipped and noted, never thrown', () => {
  const dir = mkTmp('construct-inv-unreadable-');
  try {
    // .claude/skills exists as a FILE, not a directory: readdirSync on it
    // throws ENOTDIR, standing in for any fs error a real permission-denied
    // subdirectory would raise.
    write(path.join(dir, '.claude', 'skills'), 'not a directory');
    const notes: string[] = [];
    const hits = scanSkillsTree(dir, notes);
    assert.deepEqual(hits, []);
    assert.equal(notes.length, 1);
    assert.match(notes[0], /skipped .*skills/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

