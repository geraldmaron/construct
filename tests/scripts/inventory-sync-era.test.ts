test('markersIn finds each generation marker independently', () => {
  assert.deepEqual(markersIn('<!-- Generated by construct sync -->'), [
    'Generated by construct sync',
  ]);
  assert.deepEqual(markersIn('depends on @geraldmaron/construct'), ['@geraldmaron/construct']);
  assert.deepEqual(markersIn('const orchestration_run = true;'), ['orchestration_run']);
});

test('markersIn returns every marker present, and none for ordinary text', () => {
  const text = 'Generated by construct sync, using @geraldmaron/construct, orchestration_run=1';
  assert.deepEqual(markersIn(text), [
    'Generated by construct sync',
    '@geraldmaron/construct',
    'orchestration_run',
  ]);
  assert.deepEqual(markersIn('an ordinary project file with no markers'), []);
  assert.deepEqual(markersIn(''), []);
});

