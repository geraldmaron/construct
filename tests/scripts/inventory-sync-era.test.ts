/**
 * tests/scripts/inventory-sync-era.test.ts — the sweep's two load-bearing
 * judgments: what counts as a marker hit, and what counts as this repo.
 *
 * Both are read-only, fixture-rooted checks. Nothing here touches a real
 * project tree or a real $HOME — every fixture is a tmpdir built and torn
 * down per test, the same shape tests/kernel/cleanup/catalog.test.ts uses for
 * the predecessor's own detection catalog.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
// @ts-expect-error — the script is plain .mjs, deliberately outside src/
import { markersIn, looksLikeConstructRepo, scanCursorRules, scanCursorMcp, scanSkillsTree, scanGithubAgents, scanGithubPrompts, scanProject, inventory } from '../../scripts/inventory-sync-era.mjs';

function mkTmp(prefix: string): string {
  return fs.mkdtempSync(path.join(os.tmpdir(), prefix));
}

function write(filePath: string, content: string): void {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
}

